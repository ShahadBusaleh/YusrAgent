_MONTHS = {
    "en": ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"),
    "ar": ("يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو", "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر"),
}


def parse_date(value) -> date | None:
    """ISO date/datetime ("2026-09-25", "2026-09-25T10:00:00Z") or the
    DD-MM-YYYY the staffing payloads use."""
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    text = str(value or "").strip().replace("Z", "+00:00")
    if not text:
        return None
    try:
        return datetime.fromisoformat(text).date()
    except ValueError:
        pass
    try:
        return datetime.strptime(text[:10], "%d-%m-%Y").date()
    except ValueError:
        return None


def format_date(value, lang: str | None = None) -> str:
    """"25 Sep 2026" / "25 سبتمبر 2026"; unparseable input comes back as-is."""
    day = parse_date(value)
    if day is None:
        return str(value or "")
    months = _MONTHS.get(lang or get_lang(), _MONTHS[DEFAULT_LANG])
    return f"{day.day:02d} {months[day.month - 1]} {day.year}"


def get_lang() -> str:
    return st.session_state.get("lang", DEFAULT_LANG)


def set_lang(lang: str) -> None:
    st.session_state["lang"] = lang


def is_rtl() -> bool:
    return get_lang() == "ar"


def t(key: str, **kwargs) -> str:
    lang = get_lang()
    table = STRINGS.get(lang) or STRINGS[DEFAULT_LANG]
    text = table.get(key)
    if text is None:
        text = STRINGS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
